function typeGreeting() {
  const now = new Date();
  const hour = now.getHours();
  let greetingKey = "welcome";
  let timeIcon = "☀️";

  if (hour >= 5 && hour < 12) {
    greetingKey = "morning";
    timeIcon = "☀️";
  } else if (hour >= 12 && hour < 18) {
    greetingKey = "afternoon";
    timeIcon = "☀️";
  } else {
    greetingKey = "evening";
    timeIcon = "🌙";
  }

  const greetingText = translations[currentLang][greetingKey];
  const textElement = document.querySelector(".welcome-text");
  const iconElement = document.querySelector(".welcome-icon");

  updateLanguageTexts();

  if (!textElement) return;

  textElement.innerText = "";
  if (iconElement) iconElement.innerText = " " + timeIcon;

  let i = 0;
  const speed = 100;

  function typeWriter() {
    if (i < greetingText.length) {
      textElement.innerText += greetingText.charAt(i);
      i++;
      setTimeout(typeWriter, speed);
    }
  }

  typeWriter();
}

