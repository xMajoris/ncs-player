searchInput.addEventListener("input", function () {
  const searchTerm = this.value.toLowerCase().trim();
  searchResults.innerHTML = "";

  if (searchTerm === "") {
    searchResults.style.display = "none";
    return;
  }

  const filteredSongs = playlist.filter(function (song) {
    return (
      song.title.toLowerCase().includes(searchTerm) ||
      song.artist.toLowerCase().includes(searchTerm)
    );
  });

  if (filteredSongs.length > 0) {
    searchResults.style.display = "block";
    filteredSongs.forEach(function (song) {
      const div = document.createElement("div");
      div.classList.add("search-result-item");
      div.dataset.file = song.file;

      const textSpan = document.createElement("span");
      textSpan.textContent = song.title + " - " + song.artist;

      const downloadBtn = document.createElement("button");
      downloadBtn.className = "download-btn";
      downloadBtn.textContent = "⬇️";
      downloadBtn.title = "Baixar esta música";
      downloadBtn.setAttribute("aria-label", "Baixar " + song.title);

      downloadBtn.addEventListener("click", function (e) {
        e.stopPropagation();
        downloadSong(song.file, song.title, song.artist);
      });

      div.appendChild(textSpan);
      div.appendChild(downloadBtn);

      const downloadedSongs = JSON.parse(localStorage.getItem("downloadedSongs") || "[]");
      if (downloadedSongs.includes(song.file)) {
        const badge = document.createElement("span");
        badge.className = "downloaded-badge";
        badge.textContent = "✓ Baixado";
        div.appendChild(badge);
      }

      div.addEventListener("click", function (e) {
        if (e.target.closest(".download-btn")) return;
        const originalIndex = playlist.findIndex(function (s) {
          return s.file === song.file;
        });
        if (originalIndex !== -1) {
          currentSongIndex = originalIndex;
          loadSong(true);
        }
        searchInput.value = "";
        searchResults.style.display = "none";
      });

      searchResults.appendChild(div);
    });
  } else {
    searchResults.style.display = "none";
  }
});

document.addEventListener("click", function (e) {
  if (!searchInput.contains(e.target) && !searchResults.contains(e.target)) {
    searchResults.style.display = "none";
  }
});

